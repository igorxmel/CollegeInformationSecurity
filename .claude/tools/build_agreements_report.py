def build():
    doc = rb.new_document()
    rb.title_page(doc, "3 (часть 2)", TOPIC)

    rb.section_heading(doc, "1", "Цель работы", first=True)
    rb.para(doc, GOAL)

    rb.section_heading(doc, "2", "Краткие теоретические сведения")
    for text in THEORY:
        rb.para(doc, text)
        rb.blank(doc)

    rb.section_heading(doc, "3", "Исходные данные для анализа")
    for text in SOURCES:
        rb.para(doc, text)
        rb.blank(doc)

    rb.section_heading(doc, "4", "Сравнительный анализ соглашений")
    rb.para(doc, "Результаты сравнения приведены в таблице 1. Номера пунктов относятся "
                 "к тексту соответствующего соглашения.")
    rb.table(doc, 1, "Сравнение пользовательских соглашений", HEADER, ROWS,
             [3.2, 6.65, 6.65], size=rb.SMALL)

    rb.section_heading(doc, "5", "Вывод")
    for text in CONCLUSION:
        rb.para(doc, text)

    rb.save(doc, OUT)


if __name__ == "__main__":
    build()
